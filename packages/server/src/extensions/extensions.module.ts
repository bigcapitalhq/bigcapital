import { DynamicModule, Module } from '@nestjs/common';
import { APP_GUARD } from '@nestjs/core';
import { FeaturesModule } from '../modules/Features/Features.module';
import { ExtensionsController } from './admin/extensions.controller';
import { ExtensionBridgeRegistries } from './bridges';
import { ExtensionHostModule } from './extension-host.module';
import { StaticExtensionContextFactory } from './extension.context';
import { ExtensionEnabledGuard } from './extension.guard';
import { validateExtensions } from './extension.loader';
import { ExtensionContributionRegistry } from './extension.registry';
import { ExtensionReportsController } from './reports/extension-reports.controller';
import type { ExtensionsModuleOptions } from './extension.types';
import { ExtensionFeatureGuard } from './feature.guard';

/**
 * Public extension entry point.
 *
 * `extensions` is the deploy-time list generated by the extension CLI. When the
 * list is empty the module only installs the global enablement guard and the
 * host primitives, so core behavior is unchanged.
 */
@Module({})
export class ExtensionsModule {
  static forRoot(options: ExtensionsModuleOptions = {}): DynamicModule {
    const extensions = validateExtensions(options.extensions ?? []);
    const registry = new ExtensionContributionRegistry();
    const bridges = new ExtensionBridgeRegistries();

    // Manifest-declared definitions are registered before extension modules are
    // created, so module-time registrations are idempotent.
    extensions.forEach((extension) => {
      registry.registerManifest(extension.manifest);
    });

    const staticContextFactory = new StaticExtensionContextFactory(
      registry,
      bridges,
    );
    const extensionModules = extensions.map((extension) => {
      const definition = extension.createModule(
        staticContextFactory.create(extension.manifest),
      );

      if (isPromiseLike(definition)) {
        throw new Error(
          `Extension "${extension.manifest.id}" returned a Promise from createModule(). Async extension modules are not supported yet.`,
        );
      }

      return definition as unknown as DynamicModule;
    });

    return {
      module: ExtensionsModule,
      imports: [
        ExtensionHostModule.forRoot({
          extensions,
          registry,
          bridges,
          options,
        }),
        FeaturesModule,
        ...extensionModules,
      ],
      controllers: [ExtensionReportsController, ExtensionsController],
      providers: [
        ExtensionEnabledGuard,
        ExtensionFeatureGuard,
        {
          provide: APP_GUARD,
          useClass: ExtensionEnabledGuard,
        },
        {
          provide: APP_GUARD,
          useClass: ExtensionFeatureGuard,
        },
      ],
      exports: [ExtensionHostModule, ExtensionFeatureGuard],
    };
  }
}

function isPromiseLike(value: unknown): value is Promise<unknown> {
  return (
    typeof value === 'object' &&
    value !== null &&
    typeof (value as Promise<unknown>).then === 'function'
  );
}
