import { Inject, Injectable } from '@nestjs/common';
import { Knex } from 'knex';
import { TenantModelProxy } from '@/modules/System/models/TenantBaseModel';
import { TenancyContext } from '@/modules/Tenancy/TenancyContext.service';
import { UnitOfWork } from '@/modules/Tenancy/TenancyDB/UnitOfWork.service';
import { ServiceError } from '@/modules/Items/ServiceError';
import { AutoIncrementOrdersService } from '@/modules/AutoIncrementOrders/AutoIncrementOrders.service';
import { CreateManualJournalService } from '@/modules/ManualJournals/commands/CreateManualJournal.service';
import { CreateManualJournalDto } from '@/modules/ManualJournals/dtos/ManualJournal.dto';
import { ManualJournal } from '@/modules/ManualJournals/models/ManualJournal';
import { RecurringJournal } from '../models/RecurringJournal';
import { ERRORS, RecurringJournalStatus } from '../RecurringJournal.types';
import { addOccurrence, getTodayDate } from '@/utils/recurrence';

interface IGeneratedRecurringJournal {
  generated: boolean;
  manualJournalId?: number;
  journalDate?: string;
}

@Injectable()
export class GenerateRecurringJournal {
  constructor(
    private readonly createManualJournal: CreateManualJournalService,
    private readonly autoIncrementOrders: AutoIncrementOrdersService,
    private readonly tenancyContext: TenancyContext,
    private readonly uow: UnitOfWork,

    @Inject(RecurringJournal.name)
    private readonly recurringJournalModel: TenantModelProxy<
      typeof RecurringJournal
    >,

    @Inject(ManualJournal.name)
    private readonly manualJournalModel: TenantModelProxy<typeof ManualJournal>,
  ) {}

  /**
   * Generates all due occurrences for the given profile, capped per run.
   */
  public async generateDueJournals(
    recurringJournalId: number,
    today: string,
    limit: number = 100,
  ): Promise<number> {
    let generatedCount = 0;

    for (let index = 0; index < limit; index++) {
      const result = await this.generateScheduledOccurrence(
        recurringJournalId,
        today,
      );

      if (!result) {
        break;
      }
      if (result.generated) {
        generatedCount++;
      }
    }

    return generatedCount;
  }

  /**
   * Generates the next scheduled occurrence when it is due.
   */
  public async generateScheduledOccurrence(
    recurringJournalId: number,
    today: string,
  ): Promise<IGeneratedRecurringJournal | null> {
    return this.uow.withTransaction(async (trx: Knex.Transaction) => {
      const recurringJournal = await this.recurringJournalModel()
        .query(trx)
        .findById(recurringJournalId)
        .forUpdate()
        .withGraphFetched('entries.trackingCategories')
        .throwIfNotFound();

      if (
        recurringJournal.status !== RecurringJournalStatus.Active ||
        !recurringJournal.nextJournalDate ||
        recurringJournal.nextJournalDate > today
      ) {
        return null;
      }

      const occurrenceDate = recurringJournal.nextJournalDate;

      // The occurrence may have already been generated by a previous run
      // that crashed before advancing the schedule.
      const existingJournal = await this.manualJournalModel()
        .query(trx)
        .findOne({
          recurringJournalId,
          recurringJournalDate: occurrenceDate,
        });

      if (existingJournal) {
        await this.advanceSchedule(
          recurringJournal,
          occurrenceDate,
          trx,
          false,
        );
        return { generated: false };
      }

      const journalNumber = await this.getNextJournalNumber();
      const journalDTO = this.buildManualJournalDTO(
        recurringJournal,
        occurrenceDate,
        journalNumber,
      );

      const manualJournal = await this.createManualJournal.makeJournalEntries(
        journalDTO,
        trx,
      );

      await this.manualJournalModel()
        .query(trx)
        .patchAndFetchById(manualJournal.id, {
          recurringJournalId,
          recurringJournalDate: occurrenceDate,
        });

      await this.advanceSchedule(recurringJournal, occurrenceDate, trx, true);

      return {
        generated: true,
        manualJournalId: manualJournal.id,
        journalDate: occurrenceDate,
      };
    });
  }

  /**
   * Generates an extra journal immediately without advancing the schedule.
   */
  public async generateNow(recurringJournalId: number): Promise<ManualJournal> {
    const tenantMetadata = await this.tenancyContext.getTenantMetadata();
    const today = getTodayDate(tenantMetadata?.timezone);

    return this.uow.withTransaction(async (trx: Knex.Transaction) => {
      const recurringJournal = await this.recurringJournalModel()
        .query(trx)
        .findById(recurringJournalId)
        .forUpdate()
        .withGraphFetched('entries.trackingCategories')
        .throwIfNotFound();

      const journalNumber = await this.getNextJournalNumber();
      const journalDTO = this.buildManualJournalDTO(
        recurringJournal,
        today,
        journalNumber,
      );

      const manualJournal = await this.createManualJournal.makeJournalEntries(
        journalDTO,
        trx,
      );

      return this.manualJournalModel()
        .query(trx)
        .patchAndFetchById(manualJournal.id, {
          recurringJournalId,
          recurringJournalDate: null,
        });
    });
  }

  /**
   * Builds the create-manual-journal DTO from the recurring profile.
   */
  private buildManualJournalDTO(
    recurringJournal: RecurringJournal,
    journalDate: string,
    journalNumber: string,
  ): CreateManualJournalDto {
    return {
      date: journalDate,
      journalNumber,
      journalType: recurringJournal.journalType || 'Journal',
      basis: recurringJournal.basis as any,
      reference: recurringJournal.reference,
      description: recurringJournal.description,
      currencyCode: recurringJournal.currencyCode,
      exchangeRate: recurringJournal.exchangeRate,
      branchId: recurringJournal.branchId ?? undefined,
      publish: !!recurringJournal.autoPublish,
      entries: (recurringJournal.entries || []).map((entry, index) => ({
        index: entry.index ?? index + 1,
        credit: Number(entry.credit) || 0,
        debit: Number(entry.debit) || 0,
        accountId: entry.accountId,
        note: entry.note,
        contactId: entry.contactId,
        branchId: entry.branchId ?? recurringJournal.branchId ?? undefined,
        projectId: entry.projectId,
        trackingCategories: (entry.trackingCategories ?? []).map(
          (assignment) => ({
            categoryId: assignment.categoryId,
            optionId: assignment.optionId,
          }),
        ),
      })),
    } as unknown as CreateManualJournalDto;
  }

  /**
   * Retrieves the next manual journal number.
   */
  private async getNextJournalNumber(): Promise<string> {
    const journalNumber =
      await this.autoIncrementOrders.getNextTransactionNumber(
        'manual_journals',
      );

    if (!journalNumber) {
      throw new ServiceError(
        ERRORS.RECURRING_JOURNAL_AUTO_INCREMENT_REQUIRED,
        'Recurring journals require auto-increment journal numbers. Enable auto-increment in the manual journal settings first.',
      );
    }
    return journalNumber;
  }

  /**
   * Advances the schedule after an occurrence is generated.
   */
  private async advanceSchedule(
    recurringJournal: RecurringJournal,
    occurrenceDate: string,
    trx: Knex.Transaction,
    incrementCount: boolean,
  ): Promise<void> {
    const occurrencesCount =
      Number(recurringJournal.occurrencesCount) + (incrementCount ? 1 : 0);

    let nextJournalDate: string | null = addOccurrence(
      occurrenceDate,
      recurringJournal.startDate,
      recurringJournal.frequency,
      recurringJournal.repeatInterval,
    );

    const reachedEndDate =
      !!recurringJournal.endDate && nextJournalDate > recurringJournal.endDate;
    const reachedMaxOccurrences =
      recurringJournal.maxOccurrences != null &&
      occurrencesCount >= Number(recurringJournal.maxOccurrences);

    const isCompleted = reachedEndDate || reachedMaxOccurrences;
    if (isCompleted) {
      nextJournalDate = null;
    }

    await this.recurringJournalModel()
      .query(trx)
      .patchAndFetchById(recurringJournal.id, {
        occurrencesCount,
        lastJournalDate: occurrenceDate,
        nextJournalDate,
        status: isCompleted
          ? RecurringJournalStatus.Completed
          : RecurringJournalStatus.Active,
        failureCount: 0,
        lastError: null,
      });
  }
}
