import { Inject, Injectable } from '@nestjs/common';
import { IPaginationMeta } from '@/interfaces/Model';
import { ManualJournal } from '@/modules/ManualJournals/models/ManualJournal';
import { ManualJournalTransfromer } from '@/modules/ManualJournals/queries/ManualJournalTransformer';
import { TenantModelProxy } from '@/modules/System/models/TenantBaseModel';
import { TransformerInjectable } from '@/modules/Transformer/TransformerInjectable.service';
import { GetRecurringJournalJournalsQueryDto } from '../dtos/GetRecurringJournalJournalsQuery.dto';

@Injectable()
export class GetRecurringJournalJournals {
  constructor(
    private readonly transformer: TransformerInjectable,

    @Inject(ManualJournal.name)
    private readonly manualJournalModel: TenantModelProxy<typeof ManualJournal>,
  ) {}

  /**
   * Retrieves the journals generated by the given recurring profile.
   */
  public async getRecurringJournalJournals(
    recurringJournalId: number,
    query: GetRecurringJournalJournalsQueryDto,
  ): Promise<{ data: ManualJournal[]; pagination: IPaginationMeta }> {
    const page = query.page || 1;
    const pageSize = query.pageSize || 12;

    const { results, pagination } = await this.manualJournalModel()
      .query()
      .where('recurring_journal_id', recurringJournalId)
      .withGraphFetched('entries.account')
      .withGraphFetched('entries.contact')
      .withGraphFetched('entries.branch')
      .withGraphFetched('entries.trackingCategories')
      .orderBy('date', 'DESC')
      .orderBy('id', 'DESC')
      .pagination(page - 1, pageSize);

    const data = await this.transformer.transform(
      results,
      new ManualJournalTransfromer(),
    );

    return { data, pagination };
  }
}
