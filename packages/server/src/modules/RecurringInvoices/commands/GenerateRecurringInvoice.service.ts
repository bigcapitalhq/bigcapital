import { Inject, Injectable, Logger } from '@nestjs/common';
import { Knex } from 'knex';
import * as moment from 'moment';
import { SaleInvoice } from '@/modules/SaleInvoices/models/SaleInvoice';
import { CreateSaleInvoice } from '@/modules/SaleInvoices/commands/CreateSaleInvoice.service';
import { SendSaleInvoiceMail } from '@/modules/SaleInvoices/commands/SendSaleInvoiceMail';
import { SendInvoiceMailDTO } from '@/modules/SaleInvoices/SaleInvoice.types';
import { TenantModelProxy } from '@/modules/System/models/TenantBaseModel';
import { TenancyContext } from '@/modules/Tenancy/TenancyContext.service';
import { UnitOfWork } from '@/modules/Tenancy/TenancyDB/UnitOfWork.service';
import { RecurringInvoice } from '../models/RecurringInvoice';
import { CreateSaleInvoiceDto } from '@/modules/SaleInvoices/dtos/SaleInvoice.dto';
import { ItemEntry } from '@/modules/TransactionItemEntry/models/ItemEntry';
import {
  RecurringInvoiceDeliveryMode,
  RecurringInvoiceStatus,
} from '../RecurringInvoice.types';
import {
  addOccurrence,
  getTodayDate,
  RECURRENCE_DATE_FORMAT,
} from '../utils/recurrence';

interface IGeneratedRecurringInvoice {
  generated: boolean;
  invoiceId?: number;
  invoiceDate?: string;
}

@Injectable()
export class GenerateRecurringInvoice {
  private readonly logger = new Logger(GenerateRecurringInvoice.name);

  constructor(
    private readonly createSaleInvoice: CreateSaleInvoice,
    private readonly sendSaleInvoiceMail: SendSaleInvoiceMail,
    private readonly tenancyContext: TenancyContext,
    private readonly uow: UnitOfWork,

    @Inject(RecurringInvoice.name)
    private readonly recurringInvoiceModel: TenantModelProxy<
      typeof RecurringInvoice
    >,

    @Inject(SaleInvoice.name)
    private readonly saleInvoiceModel: TenantModelProxy<typeof SaleInvoice>,
  ) {}

  /**
   * Generates all due occurrences for the given profile, capped per run.
   * @param {number} recurringInvoiceId
   * @param {string} today
   * @param {number} limit
   * @returns {Promise<number>} Number of generated invoices.
   */
  public async generateDueInvoices(
    recurringInvoiceId: number,
    today: string,
    limit: number = 100,
  ): Promise<number> {
    let generatedCount = 0;

    for (let index = 0; index < limit; index++) {
      const result = await this.generateScheduledOccurrence(
        recurringInvoiceId,
        today,
      );

      if (!result) {
        break;
      }
      if (result.generated) {
        generatedCount++;
      }
    }

    return generatedCount;
  }

  /**
   * Generates the next scheduled occurrence when it is due.
   * @param {number} recurringInvoiceId
   * @param {string} today
   * @returns {Promise<IGeneratedRecurringInvoice | null>}
   */
  public async generateScheduledOccurrence(
    recurringInvoiceId: number,
    today: string,
  ): Promise<IGeneratedRecurringInvoice | null> {
    const result = await this.uow.withTransaction(
      async (trx: Knex.Transaction) => {
        const recurringInvoice = await this.recurringInvoiceModel()
          .query(trx)
          .findById(recurringInvoiceId)
          .forUpdate()
          .withGraphFetched('entries')
          .throwIfNotFound();

        if (
          recurringInvoice.status !== RecurringInvoiceStatus.Active ||
          !recurringInvoice.nextInvoiceDate ||
          recurringInvoice.nextInvoiceDate > today
        ) {
          return null;
        }

        const occurrenceDate = recurringInvoice.nextInvoiceDate;

        // The occurrence may have already been generated by a previous run
        // that crashed before advancing the schedule.
        const existingInvoice = await this.saleInvoiceModel()
          .query(trx)
          .findOne({
            recurringInvoiceId,
            recurringInvoiceDate: occurrenceDate,
          });

        if (existingInvoice) {
          await this.advanceSchedule(
            recurringInvoice,
            occurrenceDate,
            trx,
            false,
          );
          return { generated: false };
        }

        const invoiceDTO = this.buildInvoiceDTO(
          recurringInvoice,
          occurrenceDate,
        );
        const saleInvoice = await this.createSaleInvoice.createSaleInvoice(
          invoiceDTO,
          trx,
        );

        await this.saleInvoiceModel()
          .query(trx)
          .patchAndFetchById(saleInvoice.id, {
            recurringInvoiceId,
            recurringInvoiceDate: occurrenceDate,
          });

        await this.advanceSchedule(recurringInvoice, occurrenceDate, trx, true);

        return {
          generated: true,
          invoiceId: saleInvoice.id,
          invoiceDate: occurrenceDate,
        };
      },
    );

    if (result?.generated && result.invoiceId) {
      await this.sendInvoiceEmailIfNeeded(recurringInvoiceId, result.invoiceId);
    }

    return result;
  }

  /**
   * Generates an extra invoice immediately without advancing the schedule.
   * @param {number} recurringInvoiceId
   * @returns {Promise<SaleInvoice>}
   */
  public async generateNow(recurringInvoiceId: number): Promise<SaleInvoice> {
    const tenantMetadata = await this.tenancyContext.getTenantMetadata();
    const today = getTodayDate(tenantMetadata?.timezone);

    const saleInvoice = await this.uow.withTransaction(
      async (trx: Knex.Transaction) => {
        const recurringInvoice = await this.recurringInvoiceModel()
          .query(trx)
          .findById(recurringInvoiceId)
          .forUpdate()
          .withGraphFetched('entries')
          .throwIfNotFound();

        const invoiceDTO = this.buildInvoiceDTO(recurringInvoice, today);
        const invoice = await this.createSaleInvoice.createSaleInvoice(
          invoiceDTO,
          trx,
        );

        await this.saleInvoiceModel().query(trx).patchAndFetchById(invoice.id, {
          recurringInvoiceId,
          recurringInvoiceDate: null,
        });

        return invoice;
      },
    );

    await this.sendInvoiceEmailIfNeeded(recurringInvoiceId, saleInvoice.id);

    return saleInvoice;
  }

  /**
   * Builds the create-invoice DTO from the recurring profile.
   */
  private buildInvoiceDTO(
    recurringInvoice: RecurringInvoice,
    invoiceDate: string,
  ): CreateSaleInvoiceDto {
    const dueDate = moment(invoiceDate, RECURRENCE_DATE_FORMAT)
      .add(Number(recurringInvoice.dueDays) || 0, 'day')
      .format(RECURRENCE_DATE_FORMAT);

    return {
      customerId: recurringInvoice.customerId,
      invoiceDate,
      dueDate,
      referenceNo: recurringInvoice.referenceNo,
      invoiceMessage: recurringInvoice.invoiceMessage,
      termsConditions: recurringInvoice.termsConditions,
      exchangeRate: recurringInvoice.exchangeRate,
      branchId: recurringInvoice.branchId,
      warehouseId: recurringInvoice.warehouseId,
      pdfTemplateId: recurringInvoice.pdfTemplateId,
      isInclusiveTax: recurringInvoice.isInclusiveTax,
      discount: recurringInvoice.discount,
      discountType: recurringInvoice.discountType,
      adjustment: recurringInvoice.adjustment,
      delivered: false,
      entries: (recurringInvoice.entries || []).map(
        (entry: ItemEntry, index: number) => ({
          index: entry.index ?? index,
          itemId: entry.itemId,
          description: entry.description,
          quantity: entry.quantity,
          rate: entry.rate,
          discount: entry.discount,
          discountType: entry.discountType,
          taxRateId: entry.taxRateId,
          warehouseId: entry.warehouseId,
          sellAccountId: entry.sellAccountId,
          costAccountId: entry.costAccountId,
        }),
      ),
    } as unknown as CreateSaleInvoiceDto;
  }

  /**
   * Advances the schedule after an occurrence is generated.
   */
  private async advanceSchedule(
    recurringInvoice: RecurringInvoice,
    occurrenceDate: string,
    trx: Knex.Transaction,
    incrementCount: boolean,
  ): Promise<void> {
    const occurrencesCount =
      Number(recurringInvoice.occurrencesCount) + (incrementCount ? 1 : 0);

    let nextInvoiceDate: string | null = addOccurrence(
      occurrenceDate,
      recurringInvoice.startDate,
      recurringInvoice.frequency,
      recurringInvoice.repeatInterval,
    );

    const reachedEndDate =
      !!recurringInvoice.endDate && nextInvoiceDate > recurringInvoice.endDate;
    const reachedMaxOccurrences =
      recurringInvoice.maxOccurrences != null &&
      occurrencesCount >= Number(recurringInvoice.maxOccurrences);

    const isCompleted = reachedEndDate || reachedMaxOccurrences;
    if (isCompleted) {
      nextInvoiceDate = null;
    }

    await this.recurringInvoiceModel()
      .query(trx)
      .patchAndFetchById(recurringInvoice.id, {
        occurrencesCount,
        lastInvoiceDate: occurrenceDate,
        nextInvoiceDate,
        status: isCompleted
          ? RecurringInvoiceStatus.Completed
          : RecurringInvoiceStatus.Active,
        failureCount: 0,
        lastError: null,
      });
  }

  /**
   * Sends the generated invoice email when the profile is configured to.
   */
  private async sendInvoiceEmailIfNeeded(
    recurringInvoiceId: number,
    saleInvoiceId: number,
  ): Promise<void> {
    const recurringInvoice = await this.recurringInvoiceModel()
      .query()
      .findById(recurringInvoiceId);

    if (
      !recurringInvoice ||
      recurringInvoice.deliveryMode !== RecurringInvoiceDeliveryMode.Email
    ) {
      return;
    }

    const messageOptions: SendInvoiceMailDTO = {
      subject: recurringInvoice.emailSubject || undefined,
      message: recurringInvoice.emailMessage || undefined,
      cc: recurringInvoice.emailCc || undefined,
      bcc: recurringInvoice.emailBcc || undefined,
      attachInvoice: recurringInvoice.attachInvoice ?? true,
    };

    try {
      await this.sendSaleInvoiceMail.triggerMail(
        saleInvoiceId,
        messageOptions,
        {
          attempts: 3,
          backoff: { type: 'exponential', delay: 5000 },
          removeOnComplete: true,
        },
      );
    } catch (error) {
      this.logger.error(
        `Failed to enqueue recurring invoice email for invoice ${saleInvoiceId}`,
        error instanceof Error ? error.stack : String(error),
      );

      // The invoice is created as a draft; the user can resend it manually.
      await this.recurringInvoiceModel()
        .query()
        .patchAndFetchById(recurringInvoiceId, {
          lastError:
            error instanceof Error
              ? error.message
              : 'Failed to enqueue invoice email.',
        });
    }
  }
}
