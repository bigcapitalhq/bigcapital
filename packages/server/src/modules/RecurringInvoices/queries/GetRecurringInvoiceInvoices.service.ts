import { Inject, Injectable } from '@nestjs/common';
import { IPaginationMeta } from '@/interfaces/Model';
import { SaleInvoice } from '@/modules/SaleInvoices/models/SaleInvoice';
import { SaleInvoiceTransformer } from '@/modules/SaleInvoices/queries/SaleInvoice.transformer';
import { TenantModelProxy } from '@/modules/System/models/TenantBaseModel';
import { TransformerInjectable } from '@/modules/Transformer/TransformerInjectable.service';
import { GetRecurringInvoiceInvoicesQueryDto } from '../dtos/GetRecurringInvoiceInvoicesQuery.dto';

@Injectable()
export class GetRecurringInvoiceInvoices {
  constructor(
    private readonly transformer: TransformerInjectable,

    @Inject(SaleInvoice.name)
    private readonly saleInvoiceModel: TenantModelProxy<typeof SaleInvoice>,
  ) {}

  /**
   * Retrieves the invoices generated by the given recurring profile.
   */
  public async getRecurringInvoiceInvoices(
    recurringInvoiceId: number,
    query: GetRecurringInvoiceInvoicesQueryDto,
  ): Promise<{ data: SaleInvoice[]; pagination: IPaginationMeta }> {
    const page = query.page || 1;
    const pageSize = query.pageSize || 12;

    const { results, pagination } = await this.saleInvoiceModel()
      .query()
      .where('recurring_invoice_id', recurringInvoiceId)
      .withGraphFetched('entries.item')
      .withGraphFetched('customer')
      .orderBy('invoice_date', 'DESC')
      .pagination(page - 1, pageSize);

    const data = await this.transformer.transform(
      results,
      new SaleInvoiceTransformer(),
    );

    return { data, pagination };
  }
}
